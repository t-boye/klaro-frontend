function get(obj, path) {
  return path.split('.').reduce((acc, k) => acc?.[k], obj);
}

export function getLang() {
  return localStorage.getItem('klaro_lang') || 'en';
}

export function setLang(lang) {
  localStorage.setItem('klaro_lang', lang);
  window.dispatchEvent(new CustomEvent('klaro_lang_change', { detail: lang }));
}

export function t(path, lang) {
  const l = lang || getLang();
  return get(TRANSLATIONS[l], path) || get(TRANSLATIONS.en, path) || path;
}

